/* 小分子座標（鍵長約 1 單位的示意結構）：兒茶酚胺、吲哚胺、花生油酸與攝護腺素 */
const MOLS = (function () {
  // 苯環（側鏈在 C1，3、4 位置可接 OH）
  function catechol(kind) {
    const A = [], B = [], ad = (x, y, z, el = 'C') => (A.push([x, y, z || 0, el]), A.length - 1);
    const R = []; for (let k = 0; k < 6; k++) R.push(ad(Math.cos(k * Math.PI / 3), Math.sin(k * Math.PI / 3), 0));
    for (let k = 0; k < 6; k++) B.push([R[k], R[(k + 1) % 6], k % 2 === 0 ? 2 : 1]);
    const o4 = ad(-2, 0, 0, 'O'); B.push([R[3], o4, 1]);
    if (kind !== 'Tyr') { const o3 = ad(-1, 1.732, 0, 'O'); B.push([R[2], o3, 1]); }
    const cb = ad(1.866, 0.5, 0.15), ca = ad(2.732, 0, 0.3); B.push([R[0], cb, 1], [cb, ca, 1]);
    if (kind === 'Tyr' || kind === 'DOPA') {
      const n = ad(2.732, -1, 0.6, 'N'), c = ad(3.598, 0.5, 0.3), o1 = ad(3.598, 1.5, 0.3, 'O'), o2 = ad(4.464, 0, 0.3, 'O');
      B.push([ca, n, 1], [ca, c, 1], [c, o1, 2], [c, o2, 1]);
    } else {
      const n = ad(3.598, 0.5, 0.3, 'N'); B.push([ca, n, 1]);
      if (kind === 'NE' || kind === 'Epi') { const ob = ad(1.866, 1.5, 0.5, 'O'); B.push([cb, ob, 1]); }
      if (kind === 'Epi') { const cm = ad(4.464, 0, 0.3); B.push([n, cm, 1]); }
    }
    return { atoms: A, bonds: B };
  }
  // 吲哚（色胺酸、5-羥色胺酸、血清素、N-乙醯血清素、褪黑素）
  function indole(kind) {
    const A = [], B = [], ad = (x, y, z, el = 'C') => (A.push([x, y, z || 0, el]), A.length - 1);
    const b30 = ad(0.866, 0.5), b90 = ad(0, 1), b150 = ad(-0.866, 0.5), b210 = ad(-0.866, -0.5), b270 = ad(0, -1), b330 = ad(0.866, -0.5);
    const c3 = ad(1.817, 0.809), c2 = ad(2.405, 0), n1 = ad(1.817, -0.809, 0, 'N');
    B.push([b30, b90, 1], [b90, b150, 2], [b150, b210, 1], [b210, b270, 2], [b270, b330, 1], [b330, b30, 2], [b30, c3, 1], [c3, c2, 2], [c2, n1, 1], [n1, b330, 1]);
    if (kind !== 'Trp') { const o5 = ad(-1.732, 1.0, 0, 'O'); B.push([b150, o5, 1]); if (kind === 'MEL') { const cm = ad(-2.598, 0.5, 0.2); B.push([o5, cm, 1]); } }
    const cb = ad(2.317, 1.675, 0.2), ca = ad(3.317, 1.675, 0.4), n = ad(3.817, 2.541, 0.5, 'N'); B.push([c3, cb, 1], [cb, ca, 1], [ca, n, 1]);
    if (kind === 'Trp' || kind === 'HTP') { const c = ad(3.817, 0.809, 0.6), o1 = ad(3.317, -0.06, 0.7, 'O'), o2 = ad(4.817, 0.809, 0.6, 'O'); B.push([ca, c, 1], [c, o1, 2], [c, o2, 1]); }
    if (kind === 'NAS' || kind === 'MEL') { const c = ad(4.817, 2.541, 0.5), o = ad(5.317, 3.407, 0.5, 'O'), cm = ad(5.317, 1.675, 0.5); B.push([n, c, 1], [c, o, 2], [c, cm, 1]); }
    return { atoms: A, bonds: B };
  }
  // 攝護腺素 F2α：C1–C20（索引 0–19）＋ O1a O1b O9 O11 O15（索引 20–24）
  const PG = [[6.73, 1.0, 0.3], [5.87, 0.5, 0.3], [5.0, 1.0, 0.3], [4.15, 0.5, 0.3], [3.28, 1.0, 0.3], [2.42, 0.5, 0.3], [1.55, 1.0, 0.2],
    [0.688, 0.5, 0.05], [-0.263, 0.809, 0], [-0.851, 0, 0], [-0.263, -0.809, 0], [0.688, -0.5, -0.05],
    [1.55, -1.0, -0.2], [2.42, -0.5, -0.3], [3.28, -1.0, -0.3], [4.15, -0.5, -0.3], [5.0, -1.0, -0.3], [5.87, -0.5, -0.3], [6.73, -1.0, -0.3], [7.6, -0.5, -0.3],
    [6.73, 2.0, 0.3], [7.6, 0.5, 0.3], [-0.6, 1.75, 0.4], [-0.6, -1.75, 0.4], [3.28, -2.0, -0.6]];
  // 花生油酸（同索引；環尚未閉合，羥基不存在）
  const AA = [[6.73, 1.0, 0.3], [5.87, 0.5, 0.3], [5.0, 1.0, 0.3], [4.15, 0.5, 0.3], [3.28, 1.0, 0.3], [2.42, 0.5, 0.3], [1.55, 1.0, 0.2],
    [0.75, 1.55, 0.1], [-0.2, 1.3, 0], [-0.95, 0.5, 0], [-0.75, -0.45, 0], [0.15, -0.95, -0.05],
    [1.0, -1.45, -0.2], [1.9, -0.95, -0.3], [2.75, -1.45, -0.3], [3.6, -0.95, -0.3], [4.45, -1.45, -0.3], [5.3, -0.95, -0.3], [6.15, -1.45, -0.3], [7.0, -0.95, -0.3],
    [6.73, 2.0, 0.3], [7.6, 0.5, 0.3], [-0.2, 1.3, 0], [-0.75, -0.45, 0], [2.75, -1.45, -0.3]];
  const EL = i => i >= 20 ? 'O' : 'C';
  const chainB = []; for (let i = 0; i < 19; i++) chainB.push([i, i + 1]);
  const PG_B = chainB.map(([a, b]) => [a, b, (a === 4 && b === 5) || (a === 12 && b === 13) ? 2 : 1]).concat([[7, 11, 1], [0, 20, 2], [0, 21, 1], [8, 22, 1], [10, 23, 1], [14, 24, 1]]);
  const AA_B = chainB.map(([a, b]) => [a, b, [4, 7, 10, 13].includes(a) ? 2 : 1]).concat([[0, 20, 2], [0, 21, 1]]);
  function pg() { return { atoms: PG.map((p, i) => [...p, EL(i)]), bonds: PG_B }; }
  function aa() { return { atoms: AA.slice(0, 22).map((p, i) => [...p, EL(i)]), bonds: AA_B }; }
  return { catechol, indole, pg, aa, PG, AA, PG_B, AA_B };
})();
